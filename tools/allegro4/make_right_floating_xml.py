"""Generate ``right_hand_floating.xml`` from the upstream ``right_hand.xml``.

This applies to the genuine right-hand MJCF exactly the edits that turned the
upstream ``left_hand.xml`` into the repository's ``left_hand_floating.xml``:

1. add the ``base_slide`` / ``base_hinge`` default classes (same values),
2. add six chained base joints (``base_x/y/z``, ``base_roll/pitch/yaw``) on the
   palm body,
3. add the non-colliding ``*_tip_head`` keypoint bodies (same offsets as left),
4. comment out the XML finger actuators (Python ``BuiltinPositionActuatorCfg``
   provides them, as for the left hand) and add the six base position actuators.

No geometry, joint axis, limit or inertia of the right hand is changed.  The
script is deterministic and asserts every anchor it edits.

Usage: python make_right_floating_xml.py <xmls_dir>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

BASE_DEFAULTS = """      <default class="base_slide">
        <joint type="slide" axis="1 0 0" range="-0.50 0.50" damping="3.0" armature="0.02"/>
        <position kp="300.0" kv="40.0" ctrlrange="-0.50 0.50" forcerange="-200 200"/>
      </default>
      <default class="base_hinge">
        <joint type="hinge" axis="1 0 0" range="-0.7853 0.7853" damping="0.5" armature="0.01"/>
        <position kp="60.0" kv="8.0" ctrlrange="-0.7853 0.7853" forcerange="-80 80"/>
      </default>
"""

BASE_JOINTS = """      <joint name="base_x" class="base_slide" axis="1 0 0"/>
      <joint name="base_y" class="base_slide" axis="0 1 0"/>
      <joint name="base_z" class="base_slide" axis="0 0 1"/>
      <joint name="base_roll" class="base_hinge" axis="1 0 0"/>
      <joint name="base_pitch" class="base_hinge" axis="0 1 0"/>
      <joint name="base_yaw" class="base_hinge" axis="0 0 1"/>

"""

BASE_ACTUATORS = """  <actuator>
    <position name="base_x_act" joint="base_x" class="base_slide"/>
    <position name="base_y_act" joint="base_y" class="base_slide"/>
    <position name="base_z_act" joint="base_z" class="base_slide"/>
    <position name="base_roll_act" joint="base_roll" class="base_hinge"/>
    <position name="base_pitch_act" joint="base_pitch" class="base_hinge"/>
    <position name="base_yaw_act" joint="base_yaw" class="base_hinge"/>
  </actuator>
"""

# Same offsets/colors as left_hand_floating.xml.
TIP_HEADS = {
    "rf": ("0 0 0.035", "1 0 0 0.5"),
    "mf": ("0 0 0.035", "0 1 0 0.5"),
    "ff": ("0 0 0.035", "0 0 1 0.5"),
    "th": ("0 0 0.050", "1 1 0 0.5"),
}


def _replace_once(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count != 1:
        raise AssertionError(f"anchor found {count} times: {old!r}")
    return text.replace(old, new)


def make(src: str) -> str:
    out = src
    # 1. defaults: insert after the thumb_distal default block.
    anchor = (
        '      <default class="thumb_distal">\n'
        '        <joint range="-0.162 1.719"/>\n'
        '        <position ctrlrange="-0.162 1.719"/>\n'
        "      </default>\n"
    )
    out = _replace_once(out, anchor, anchor + BASE_DEFAULTS)
    # 2. base joints on the palm body.
    palm = '    <body name="palm" quat="0 1 0 1" childclass="allegro_right">\n'
    out = _replace_once(out, palm, palm + BASE_JOINTS)
    # 3. tip heads.
    for finger, (pos, rgba) in TIP_HEADS.items():
        tip_geom = "thumbtip_collision" if finger == "th" else "fingertip_collision"
        pattern = re.compile(
            rf'(<body name="{finger}_tip">\n(\s*)<geom class="\w+"/>\n\s*<geom class="{tip_geom}"/>\n)'
        )
        matches = pattern.findall(out)
        if len(matches) != 1:
            raise AssertionError(f"tip anchor for {finger}: {len(matches)} matches")
        indent = matches[0][1]
        head = (
            f"{indent}<!-- Virtual tip head for visualization/contact -->\n"
            f'{indent}<body name="{finger}_tip_head" pos="{pos}">\n'
            f'{indent}  <geom type="sphere" size="0.005" contype="0" conaffinity="0" '
            f'group="4" rgba="{rgba}"/>\n'
            f"{indent}</body>\n"
        )
        out = pattern.sub(lambda m: m.group(1) + head, out, count=1)
    # 4. actuators.
    start = out.index("  <actuator>\n")
    end = out.index("  </actuator>\n") + len("  </actuator>\n")
    finger_act = out[start:end]
    if finger_act.count("<position") != 16:
        raise AssertionError("expected 16 finger actuators in right_hand.xml")
    commented = "  <!-- " + finger_act[2:].rstrip("\n") + " -->\n"
    out = out[:start] + commented + BASE_ACTUATORS + out[end:]
    return out


def main() -> None:
    xmls = Path(sys.argv[1])
    src = (xmls / "right_hand.xml").read_text()
    dst = xmls / "right_hand_floating.xml"
    text = make(src)
    header = (
        "<!-- Generated by tools/allegro4/make_right_floating_xml.py from right_hand.xml;\n"
        "     mirrors the left_hand.xml -> left_hand_floating.xml edits. Do not hand-edit. -->\n"
    )
    dst.write_text(header + text)
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
